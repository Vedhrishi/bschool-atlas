// Builds data/world.js: simplified country outlines grouped by continent.
// Source: Natural Earth (public domain) via the world-atlas package.
const fs = require('fs');
const path = require('path');
const topo = require('topojson-client');
const { geoNaturalEarth1, geoPath } = require('d3-geo');
const iso = require('i18n-iso-countries');
const { countries: meta } = require('countries-list');

const W = 1000, H = 520;
const world = JSON.parse(fs.readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8'));
const feats = topo.feature(world, world.objects.countries).features;
const projection = geoNaturalEarth1().fitExtent([[6, 6], [W - 6, H - 6]], { type: 'FeatureCollection', features: feats.filter((f) => f.properties.name !== 'Antarctica') });
const gen = geoPath(projection).digits(1);

const NAMES = { AF: 'Africa', AS: 'Asia', EU: 'Europe', NA: 'North America', OC: 'Oceania', SA: 'South America' };
const out = [];
const skipped = [];
for (const f of feats) {
  const a2 = iso.numericToAlpha2(String(f.id).padStart(3, '0'));
  const m = a2 && meta[a2];
  if (!m || m.continent === 'AN') { skipped.push(f.properties.name); continue; }
  const d = gen(f);
  if (!d) continue;
  out.push({ id: a2, name: f.properties.name, continent: m.continent, d });
}
const bounds = {};
for (const c of Object.keys(NAMES)) {
  const set = feats.filter((f) => { const a2 = iso.numericToAlpha2(String(f.id).padStart(3, '0')); return a2 && meta[a2] && meta[a2].continent === c; });
  // Mainland-focused bounds: ignore far-flung islands by clipping to the median of centroids.
  const [[x0, y0], [x1, y1]] = geoPath(projection).bounds({ type: 'FeatureCollection', features: set });
  bounds[c] = [x0, y0, x1, y1].map((v) => Math.round(v));
}
// City dots for the programmes in data/countries.js, projected with the same projection.
const CITIES = [
  ['IN', 'Hyderabad', 78.4867, 17.385], ['CN', 'Shanghai', 121.4737, 31.2304], ['GB', 'London', -0.1278, 51.5074],
  ['FR', 'Fontainebleau', 2.7016, 48.4047], ['ES', 'Madrid', -3.7038, 40.4168], ['US', 'Stanford', -122.1697, 37.4275],
  ['CA', 'Toronto', -79.3832, 43.6532], ['AU', 'Sydney', 151.2093, -33.8688], ['ZA', 'Cape Town', 18.4241, -33.9249],
];
const cities = CITIES.map(([id, name, lon, lat]) => { const [x, y] = projection([lon, lat]); return { id, name, x: +x.toFixed(1), y: +y.toFixed(1) }; });
const js = '// Generated by scripts/build-map.js from Natural Earth (public domain). Do not edit.\n' +
  'window.WORLD = ' + JSON.stringify({ width: W, height: H, continents: NAMES, bounds, cities, countries: out }) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'data', 'world.js'), js);
console.log('countries:', out.length, 'skipped:', skipped.join(', '), 'bytes:', js.length);
console.log(bounds);
